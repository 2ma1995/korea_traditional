const INGREDIENT_SET = new Set(INGREDIENTS);

/** 접미어를 떼고 기본 재료인지 본다 */
function matchesBase(word: string): boolean {
  if (INGREDIENT_SET.has(word)) return true;
  return SUFFIXES.some(
    (suffix) => word.length > suffix.length && word.endsWith(suffix) && INGREDIENT_SET.has(word.slice(0, -suffix.length)),
  );
}

/** 접두어·접미어를 감안해 사전에 있는 재료인지 판정한다 */
export function isKnownIngredient(name: string): boolean {
  const compact = name.replace(/\s+/g, '');
  if (matchesBase(compact)) return true;
  return PREFIXES.some((prefix) => compact.startsWith(prefix) && matchesBase(compact.slice(prefix.length)));
}
